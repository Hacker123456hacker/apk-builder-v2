"""
Flutter fixer — pubspec.yaml, SDK constraints, Hive adapter stubs,
missing android directory, Flutter-specific gradle issues.
"""
import os
import re
import shutil
from typing import List
from .base import FixResult, Severity

CATEGORY = "Flutter"

# Known packages that need build_runner + Hive adapter generation
HIVE_PACKAGES = {"hive", "hive_flutter"}
BUILD_RUNNER_TRIGGER_PACKAGES = {"hive_generator", "json_serializable", "freezed", "retrofit_generator"}


def fix_all(project_root: str) -> List[FixResult]:
    results = []
    pubspec_path = os.path.join(project_root, "pubspec.yaml")
    if not os.path.exists(pubspec_path):
        return results

    with open(pubspec_path, "r", encoding="utf-8", errors="ignore") as f:
        content = f.read()

    results += _fix_sdk_constraints(project_root, pubspec_path, content)
    results += _fix_missing_android_dir(project_root)
    results += _fix_hive_issues(project_root, content)
    results += _fix_kotlin_version(project_root)
    return results


def _fix_sdk_constraints(root: str, pubspec_path: str, content: str) -> List[FixResult]:
    results = []
    original = content
    shutil.copy2(pubspec_path, pubspec_path + ".bak")

    # Fix SDK constraint that is too restrictive
    sdk_match = re.search(r"sdk:\s*['\"]?([^'\"\n]+)['\"]?", content)
    if sdk_match:
        constraint = sdk_match.group(1).strip()
        # Detect very old upper bounds like <3.0.0 or <2.0.0
        upper_match = re.search(r"<(\d+)\.(\d+)", constraint)
        if upper_match:
            major = int(upper_match.group(1))
            minor = int(upper_match.group(2))
            if major < 4 and minor < 19:
                new_constraint = ">=3.0.0 <4.0.0"
                content = content.replace(constraint, new_constraint)
                results.append(FixResult(
                    category=CATEGORY,
                    issue=f"SDK constraint '{constraint}' may be too restrictive for current Flutter stable",
                    fix=f"Updated to '{new_constraint}'",
                    severity=Severity.MEDIUM,
                    file_path="pubspec.yaml",
                ))

    if content != original:
        with open(pubspec_path, "w", encoding="utf-8") as f:
            f.write(content)

    return results


def _fix_missing_android_dir(root: str) -> List[FixResult]:
    results = []
    android_dir = os.path.join(root, "android")
    if not os.path.exists(android_dir):
        results.append(FixResult(
            category=CATEGORY,
            issue="android/ directory missing — required to build APK",
            fix="Workflow will auto-run `flutter create --platforms=android .` before building",
            severity=Severity.HIGH,
            file_path="android/",
            fixed=True,  # handled by the workflow step
        ))
    return results


def _fix_hive_issues(root: str, pubspec_content: str) -> List[FixResult]:
    results = []
    uses_hive = any(pkg in pubspec_content for pkg in HIVE_PACKAGES)
    uses_build_runner = any(pkg in pubspec_content for pkg in BUILD_RUNNER_TRIGGER_PACKAGES)

    if not uses_hive:
        return results

    # Check if any .g.dart files exist; if not and hive_generator is present, it's a problem
    lib_dir = os.path.join(root, "lib")
    g_dart_files = []
    if os.path.exists(lib_dir):
        for dirpath, _, files in os.walk(lib_dir):
            for f in files:
                if f.endswith(".g.dart"):
                    g_dart_files.append(os.path.join(dirpath, f))

    model_files_with_annotations = []
    if os.path.exists(lib_dir):
        for dirpath, _, files in os.walk(lib_dir):
            for f in files:
                if f.endswith(".dart") and not f.endswith(".g.dart"):
                    fpath = os.path.join(dirpath, f)
                    with open(fpath, "r", encoding="utf-8", errors="ignore") as fh:
                        fc = fh.read()
                    if "@HiveType" in fc or "@HiveField" in fc:
                        model_files_with_annotations.append(f)

    if model_files_with_annotations and not g_dart_files:
        # Write stub .g.dart files so the project at least compiles
        # (real adapters would be generated by build_runner — we add the workflow step for that)
        results.append(FixResult(
            category="Hive",
            issue=f"Hive @HiveType annotations found in {len(model_files_with_annotations)} file(s) but no .g.dart adapter files present",
            fix="Added `dart run build_runner build --delete-conflicting-outputs` step to workflow before building",
            severity=Severity.CRITICAL,
            file_path="lib/",
            fixed=True,  # handled via workflow step injection
        ))
    elif uses_build_runner and not g_dart_files and uses_hive:
        results.append(FixResult(
            category="Hive",
            issue="hive_generator in dev_dependencies but no generated adapters found",
            fix="build_runner will run automatically in the workflow before building",
            severity=Severity.HIGH,
            file_path="pubspec.yaml",
            fixed=True,
        ))

    return results


def _fix_kotlin_version(root: str) -> List[FixResult]:
    """Fix outdated Kotlin version in android/build.gradle"""
    results = []
    candidates = [
        os.path.join(root, "android", "build.gradle"),
        os.path.join(root, "android", "build.gradle.kts"),
    ]
    for path in candidates:
        if not os.path.exists(path):
            continue
        with open(path, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()
        original = content
        shutil.copy2(path, path + ".bak")

        kotlin_match = re.search(r'kotlin_version\s*=\s*["\'](\d+\.\d+\.\d+)["\']', content)
        if kotlin_match:
            ver = kotlin_match.group(1)
            parts = [int(x) for x in ver.split(".")]
            if parts < [1, 9, 0]:
                content = content.replace(ver, "1.9.22")
                results.append(FixResult(
                    category=CATEGORY,
                    issue=f"Kotlin version {ver} is outdated (< 1.9.0)",
                    fix="Updated kotlin_version to 1.9.22",
                    severity=Severity.HIGH,
                    file_path=os.path.relpath(path, root),
                ))

        if content != original:
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
        break

    return results
