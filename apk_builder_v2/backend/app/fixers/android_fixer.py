"""
Android fixer — AndroidManifest.xml, namespace, SDK versions,
missing internet permission, etc.
"""
import os
import re
import shutil
from typing import List
from .base import FixResult, Severity

CATEGORY = "Android"


def fix_all(project_root: str) -> List[FixResult]:
    results = []
    results += _fix_android_manifest(project_root)
    return results


def _fix_android_manifest(root: str) -> List[FixResult]:
    results = []

    # Try both Flutter and native Android paths
    candidates = [
        os.path.join(root, "android", "app", "src", "main", "AndroidManifest.xml"),
        os.path.join(root, "app", "src", "main", "AndroidManifest.xml"),
    ]

    manifest_path = None
    for c in candidates:
        if os.path.exists(c):
            manifest_path = c
            break

    if not manifest_path:
        results.append(FixResult(
            category=CATEGORY,
            issue="AndroidManifest.xml not found",
            fix="Will be auto-generated by `flutter create` in the workflow",
            severity=Severity.HIGH,
            file_path="android/app/src/main/AndroidManifest.xml",
            fixed=True,
        ))
        return results

    with open(manifest_path, "r", encoding="utf-8", errors="ignore") as f:
        content = f.read()

    original = content
    shutil.copy2(manifest_path, manifest_path + ".bak")
    display_path = os.path.relpath(manifest_path, root)

    # Fix 1: Missing INTERNET permission (almost every app needs this)
    if "android.permission.INTERNET" not in content:
        # Insert before <application tag
        content = content.replace(
            "<application",
            '    <uses-permission android:name="android.permission.INTERNET"/>\n\n    <application',
            1
        )
        results.append(FixResult(
            category=CATEGORY,
            issue="INTERNET permission missing from AndroidManifest.xml",
            fix='Added <uses-permission android:name="android.permission.INTERNET"/>',
            severity=Severity.MEDIUM,
            file_path=display_path,
        ))

    # Fix 2: android:label missing
    if 'android:label' not in content:
        content = content.replace(
            "<application",
            '<application android:label="App"',
            1
        )
        results.append(FixResult(
            category=CATEGORY,
            issue="android:label missing from <application> tag",
            fix='Added android:label="App"',
            severity=Severity.LOW,
            file_path=display_path,
        ))

    # Fix 3: exported attribute missing on main activity (required API 31+)
    if "<activity" in content and "android:exported" not in content:
        content = re.sub(
            r"(<activity\b[^>]*)(>)",
            r'\1 android:exported="true"\2',
            content,
            count=1
        )
        results.append(FixResult(
            category=CATEGORY,
            issue="android:exported attribute missing on <activity> (required for targetSdk 31+)",
            fix='Added android:exported="true" to main activity',
            severity=Severity.HIGH,
            file_path=display_path,
        ))

    if content != original:
        with open(manifest_path, "w", encoding="utf-8") as f:
            f.write(content)

    return results
